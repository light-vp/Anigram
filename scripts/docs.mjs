const work = mkdtempSync(join(tmpdir(), 'anigram-docs-'))
// DEXPI's own reference P&ID, for import_dexpi's example
copyFileSync(
  join(root, 'src/format/fixtures/dexpi-c01-reference.xml'),
  join(work, 'reference-pid.xml'),
)
const client = new Client({ name: 'docs', version: '0' })
await client.connect(
  new StdioClientTransport({
    command: process.execPath,
    args: [join(root, 'mcp/dist/anigram-mcp.mjs')],
    cwd: work,
    stderr: 'ignore',
  }),
)

const LIMIT = 40
const clip = (text) => {
  const lines = text.replaceAll(work, '.').split('\n')
  const short = lines.map((l) => (l.length > 160 ? `${l.slice(0, 157)}...` : l))
  return short.length > LIMIT
    ? `${short.slice(0, LIMIT).join('\n')}\n... (${short.length - LIMIT} more lines)`
    : short.join('\n')
}

function params(schema) {
  const props = Object.entries(schema?.properties ?? {})
  if (!props.length) return 'No parameters.\n'
  const required = new Set(schema.required ?? [])
  let t = '| parameter | type | required | what it is |\n| - | - | - | - |\n'
  for (const [name, p] of props) {
    const type =
      p.type ??
      (p.anyOf ? p.anyOf.map((a) => a.type).join(' or ') : p.enum ? 'enum' : '')
    const values = p.enum
      ? ` One of ${p.enum.map((v) => `\`${v}\``).join(', ')}.`
      : ''
    t += `| \`${name}\` | ${type} | ${required.has(name) ? 'yes' : ''} | ${cell(p.description ?? '')}${values} |\n`
  }
  return t
}

const { tools } = await client.listTools()
// the app's docs page lists the tools by hand; it must name every one
{
  const listed = MCP_TOOLS.map(([name]) => name).sort()
  const served = tools.map((t) => t.name).sort()
  if (listed.join() !== served.join())
    throw new Error(
      `docs: MCP_TOOLS in src/site/docsContent.ts lists ${listed.join(', ')}, but the server has ${served.join(', ')}`,
    )
}
const { prompts } = await client.listPrompts()
let mcp = HEAD(
  'MCP tools',
  'Everything the `anigram-mcp` server offers an assistant, with a real call against a built-in sheet and the start of its real answer. Install it with `claude mcp add anigram -- npx -y anigram-mcp` (more in [the MCP README](../../mcp/README.md)).\n\nMost tools take a scene three ways: `id` for a built-in sheet, `file` for a scene file on disk, or `scene` for the JSON itself.',
)
mcp += `\n## Tools\n\n${tools.map((t) => `- [\`${t.name}\`](#${t.name}): ${t.title ?? ''}`).join('\n')}\n`
for (const t of tools) {
  const args = EXAMPLES[t.name]
  if (!args)
    throw new Error(
      `docs: add an example call for the new tool ${t.name} to scripts/docs.mjs`,
    )
  const r = await client.callTool({ name: t.name, arguments: args })
  if (r.isError)
    throw new Error(
      `docs: the example for ${t.name} failed: ${r.content[0]?.text}`,
    )
  const answer = r.structuredContent
    ? JSON.stringify(r.structuredContent, null, 2)
    : r.content
        .filter((c) => c.type === 'text')
        .map((c) => c.text)
        .join('\n')
  const hints = [
    t.annotations?.readOnlyHint && 'read-only',
    t.annotations?.destructiveHint && 'writes files',
  ].filter(Boolean)
  mcp += `\n## ${t.name}\n\n**${t.title ?? t.name}**${hints.length ? ` · ${hints.join(', ')}` : ''}\n\n${t.description}\n\n${params(t.inputSchema)}\n**Example**\n\n\`\`\`json\n${JSON.stringify(args, null, 2)}\n\`\`\`\n\n\`\`\`json\n${clip(answer)}\n\`\`\`\n`
}
mcp += `\n## Prompts\n\nReady-made instructions an assistant can start from, one per drawing practice.\n\n| prompt | what it's for |\n| - | - |\n${prompts.map((p) => `| \`${p.name}\` | ${cell(p.description ?? '')} |`).join('\n')}\n`
files.set('mcp-tools.md', mcp)
await client.close()
rmSync(work, { recursive: true, force: true })

// ---- write, or check --------------------------------------------------------

const existing = (() => {
  const found = new Map()
  const walk = (dir, rel = '') => {
    let entries = []
    try {
      entries = readdirSync(dir, { withFileTypes: true })
    } catch {
      return
    }
    for (const e of entries)
      if (e.isDirectory()) walk(join(dir, e.name), `${rel}${e.name}/`)
      else found.set(`${rel}${e.name}`, readFileSync(join(dir, e.name), 'utf8'))
  }
  walk(OUT)
  return found
})()

if (CHECK) {
  const stale = [...files]
    .filter(([f, text]) => existing.get(f) !== text)
    .map(([f]) => f)
  const extra = [...existing.keys()].filter((f) => !files.has(f))
  if (stale.length || extra.length) {
    console.error(
      `docs/reference/ is out of date (${[...stale, ...extra].slice(0, 8).join(', ')}). Run \`npm run docs\` and commit the result.`,
    )
    process.exit(1)
  }
  console.log(`docs/reference/ is up to date (${files.size} files)`)
} else {
  rmSync(OUT, { recursive: true, force: true })
  for (const [f, text] of files) {
    mkdirSync(join(OUT, f, '..'), { recursive: true })
    writeFileSync(join(OUT, f), text)
  }
  console.log(`wrote ${files.size} files to docs/reference/`)
}
