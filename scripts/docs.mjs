// The reference docs, written from the code so they can't drift from it:
// every part with its drawing, every engineering symbol in each symbol set,
// and every MCP tool with a real call and its real answer.
//
//   npm run docs         rewrite docs/reference/
//   npm run docs:check   fail if docs/reference/ is out of date (CI runs this)
//
// Needs the MCP server built first (`npm run build:mcp`); both scripts do it.
import {
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { Client } from '@modelcontextprotocol/sdk/client/index.js'
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js'
import { createServer } from 'vite'

const root = fileURLToPath(new URL('..', import.meta.url))
const OUT = join(root, 'docs/reference')
const CHECK = process.argv.includes('--check')

/** path → contents, written (or compared) at the end */
const files = new Map()
const HEAD = (title, intro) =>
  `<!-- Generated by \`npm run docs\` from the code. Edit the code, not this file. -->\n\n# ${title}\n\n${intro}\n`

// ---- parts and symbols ------------------------------------------------------

const vite = await createServer({
  root,
  logLevel: 'error',
  server: { middlewareMode: true, hmr: false },
  appType: 'custom',
})
const { kindSvg, classSvg } = await vite.ssrLoadModule(
  '/src/docs/symbolSheet.tsx',
)
const { PART_KINDS } = await vite.ssrLoadModule('/src/parts/kinds.ts')
const { PACKS } = await vite.ssrLoadModule('/src/packs/catalogue.ts')
const { MCP_TOOLS } = await vite.ssrLoadModule('/src/site/docsContent.ts')
await vite.close()

const GROUPS = {
  source: 'Sources',
  conversion: 'Conversion',
  switchgear: 'Switchgear and carriers',
  storage: 'Storage',
  water: 'Water',
  demand: 'Demand',
  waste: 'Waste and losses',
}

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')

let parts = HEAD(
  'Parts',
  'Every part a scene can use, as the pictorial sheet draws it. A part names its `kind` from this list; its `behaviour` decides what it does (see [the scene format](../scene-format.md)). The drawing moves with the simulation: what moves is in the last column.',
)
for (const [group, title] of Object.entries(GROUPS)) {
  const kinds = Object.entries(PART_KINDS).filter(([, k]) => k.group === group)
  if (!kinds.length) continue
  parts += `\n## ${title}\n\n| | kind | usual role | draws |\n| - | - | - | - |\n`
  for (const [kind, info] of kinds) {
    files.set(`symbols/kind-${kind}.svg`, kindSvg(kind))
    parts += `| <img src="symbols/kind-${kind}.svg" width="48" height="48" alt=""> | \`${kind}\` | ${info.role} | ${cell(info.draws)} |\n`
  }
}
files.set('parts.md', parts)

let symbols = HEAD(
  'Engineering symbols',
  'What each drawing practice draws, by symbol class. Set `drawing` on a scene to draw it in a practice; a part takes the class named in its `class` field, or the class its `kind` maps to below. Where IEC and ANSI draw a symbol differently, both are shown: set `symbols: "ansi"` on the scene for the ANSI set (IEC is the default). Anything without a symbol is drawn as a labelled block.',
)
for (const pack of Object.values(PACKS)) {
  symbols += `\n## ${pack.name} (\`drawing: "${pack.drawing}"\`)\n\nFollows ${pack.follows}. Draws ${pack.shows.join(', ')} lines.\n\n| IEC | ANSI | class | is | drawn for kinds |\n| - | - | - | - | - |\n`
  for (const [cls, info] of Object.entries(pack.classes)) {
    const iec = classSvg(cls, 'iec')
    const ansi = classSvg(cls, 'ansi')
    files.set(`symbols/${cls}.svg`, iec)
    if (ansi !== iec) files.set(`symbols/${cls}-ansi.svg`, ansi)
    const img = (f) =>
      `<img src="symbols/${f}.svg" width="48" height="48" alt="">`
    const kinds = Object.entries(pack.fromKind)
      .filter(([, c]) => c === cls)
      .map(([k]) => `\`${k}\``)
      .join(', ')
    symbols += `| ${img(cls)} | ${ansi !== iec ? img(`${cls}-ansi`) : 'same'} | \`${cls}\` | ${cell(info.is)} | ${kinds || '—'} |\n`
  }
}
files.set('symbols.md', symbols)

// ---- MCP tools --------------------------------------------------------------

